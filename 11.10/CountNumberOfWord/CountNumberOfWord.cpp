#include <iostream>
#include <string>

//Завдання 2
//Створити програму, яка підраховує точну кількість входжень певного
//слова у введеному тексті.
//Вимоги до реалізації :
//● Введення : Зчитати два рядки — довгий текст(база для
//    пошуку) та коротке слово(що шукаємо).
//    ● Пошук зі зміщенням : Використати перевантаження методу
//    find(слово, позиція_старту).За замовчуванням пошук
//    починається з 0.
//    ● Цикл : Створити цикл while, який працює, поки find не поверне
//    std::string::npos.
//    ● Логіка підрахунку : Кожного разу, коли слово знайдено,
//    збільшувати лічильник на 1, а позицію_старту для наступного
//    пошуку оновлювати як індекс_знайденого_слова +
//    довжина_слова.
//    ● Виведення : Показати загальну кількість знайдених збігів.

int main()
{
    std::string text;
    std::string word;

    std::cout << "Write Text: " << text << '\n';
    std::getline(std::cin, text);

    std::cout << "Word for search: " << word << '\n';
    std::getline(std::cin, word);

    int count = 0;
    int pos = 0;

    if (!word.empty()) {
        pos = text.find(word, pos);

        while (pos != std::string::npos) {
            count++;
            pos = text.find(word, pos + word.length());
        }
    }
    std::cout << "Into count: " << count << '\n';
}
